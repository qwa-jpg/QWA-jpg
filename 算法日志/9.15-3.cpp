// ============================================================
// POJ 1780 "Code" —— de Bruijn 序列 + 欧拉回路（手工栈 Hierholzer）
// 求包含所有 n 位十进制数的最短循环串，答案长度 10^n + n - 1
// ============================================================

#include <stdio.h>
const int N = 1e5;
int num[N];
int st_edge[10 * N], top_s;
char st_ans[10 * N]; int top_a;
int m;

void no_dfs(int v) {                 // 只做前向扩展，不递归
    while(num[v] < 10) {
        int edge = v * 10 + num[v]++;
        st_edge[top_s++] = edge;
        v = edge % m;                // 下一个点 = 边值的后 n-1 位
    }
}

int main(){
    int n, edge;
    while(scanf("%d",&n)&&n!=0){
        top_s = top_a = 0;
        m = 1;
        for(int i = 0;i < n-1;++i)  m *= 10;
        for(int i = 0;i < m; i++)  num[i] = 0;
        no_dfs(0);
        while(top_s){                          // 回溯循环放在 main
            edge = st_edge[--top_s];
            st_ans[top_a++] = edge % 10 + '0';
            no_dfs(edge/10);                   // 从边的起点继续扩展
        }
        for(int i = 1;i < n;++i) printf("0");  // n-1 个前导 0
        while(top_a) printf("%c",st_ans[--top_a]);
        printf("\n");
    }
    return 0;
}

/* ============================================================
   一、代码解释
   ============================================================

   题目模型（最关键的一步转化）
   ------------------------------------------------------------
   "求包含所有 n 位十进制数的最短循环串" = 在 de Bruijn 图上找欧拉回路。

   建图方式：
   - 点：所有 (n-1) 位数，共 m = 10^(n-1) 个点
   - 边：从点 v 出发 10 条边，边值 = v*10 + d（d = 0~9），
         即"把 v 左移一位、末位接上 d"。这条边就代表一个 n 位数 v*10+d
   - 边的终点 = v*10+d 的后 n-1 位 = edge % m

   为什么找欧拉回路就能得到答案：沿回路走，相邻两条边天然重叠 n-1 位
   （前一条边的终点 = 后一条边的起点）。回路经过 10^n 条边（= 全部 n 位数，
   每个恰好一次），把每条边新增的那一位 d 串起来，就是一个循环串。

   欧拉回路存在因为：每个点入度 = 出度 = 10（每个 (n-1) 位数 x 恰好是
   10 条边 "10a+b" 的终点，即每点恰有 10 条入边、10 条出边），且图连通。

   各变量职责
   ------------------------------------------------------------
   num[v]       点 v 已经用掉了几条边（下一个待用边的 d 值）
   st_edge[]    手工栈，存当前回路"正在走的边"
   st_ans[]     答案数字，逆序存放
   top_s/top_a  两个栈的栈顶

   为什么用栈模拟 DFS 而不是真递归
   ------------------------------------------------------------
   边数 10^n，n=6 时 10^6 条，真递归会爆栈。手工栈版本：

       void no_dfs(int v) {
           while(num[v] < 10) {            // 点 v 还有边没走
               int edge = v * 10 + num[v]++;
               st_edge[top_s++] = edge;    // 走这条边，压栈
               v = edge % m;               // 走到终点，继续向前
           }
       }

   这就是 DFS 的前向下降部分：从 v 一直贪心往前走，走到某个点 10 条边全用完
   才停（等价于递归 DFS 中"一直往下钻"）。

   main 里的回溯循环
   ------------------------------------------------------------
       while(top_s){
           edge = st_edge[--top_s];            // 弹出栈顶边 = 回溯一步
           st_ans[top_a++] = edge % 10 + '0';  // 输出这条边新增的那位 d
           no_dfs(edge/10);                    // 从这条边的起点继续扩展！
       }

   这就是 Hierholzer 的回溯部分：
   - 弹出一条边 edge，它的起点是 edge / 10（edge = v*10 + d，d<10，整除 10 得 v）
   - 起点 v 可能还有没走的边，于是 no_dfs(edge/10) 从 v 再往前钻
   - 每弹一条边输出一位 edge % 10（即 d）

   "输出"发生在回溯时，所以 st_ans 是逆序的，最后倒着打印。

   输出怎么拼
   ------------------------------------------------------------
   回路产生的 10^n 个数字（每条边一位）按回路顺序输出。但这只是"边"，
   还差开头的点：回路从点 0（n-1 个 0）出发，所以完整串 =
   n-1 个前导 0 + 10^n 条边的末位数字，总长 10^n + n - 1。
   第一条边是 0*10+0 = 0，末位又是 0，所以开头正好 n 个 0。

   以 n=2 为例，回路前几步：点0→(边0)→点0→(边1)→点1→(边10)→点0→(边2)→
   点2→(边20)→点0→… 输出 0 + 010203... = 00102030405...，正是标准答案开头。

   复杂度
   ------------------------------------------------------------
   时间 O(10^n)，空间 O(10^n)。n=6 时约 10^6 条边、10^6 个字符，
   栈数组 st_edge[10*N] 和 st_ans[10*N] 刚好够用。

   一句话总结：n 位数当边、n-1 位数当点建 de Bruijn 图 → 手工栈跑
   Hierholzer 求欧拉回路 → 回溯时输出每条边的末位 → 前面补 n-1 个 0。

   ============================================================
   二、为什么回溯的时候可能还有没走完的边
   ============================================================

   直接原因：前向走的时候"经过 ≠ 用完"
   ------------------------------------------------------------
   no_dfs 的循环体每次循环只取当前点的下一条边：

       int edge = v * 10 + num[v]++;   // 只消耗一条边
       v = edge % m;                   // 立刻离开这个点

   一个点有 10 条出边，但从它旁边经过时只带走 1 条，剩下 9 条原封不动。
   只有当某个点被经过 10 次（10 条边全用光）才会"卡住"。路径中间的点，
   绝大多数只被经过一两次，都还剩大量没走的边。

   具体例子（n=2）
   ------------------------------------------------------------
   初始从 0 前向走：

       0 --0--> 0 --1--> 1 --10--> 0 --2--> 2 --20--> 0 --3--> ... --90--> 0

   点 0 的第 10 条边用完后卡住。栈顶边是 90，它的起点是 9。点 9 到目前为止
   只走了 90 这一条（num[9]=1），91~99 九条边都没动。

   于是弹栈回溯到 9，no_dfs(9) 继续走：

       9 --91--> 1 --11--> 1 --12--> 2 --21--> 1 --13--> 3 --31--> ...

   这就是"回溯时还有没走完的边"的实例。

   为什么"卡住"一定发生在起点（机制成立的关键）
   ------------------------------------------------------------
   假设贪心走卡在了非起点 w：每个点经过时消耗一条入边、一条出边，而终点 w
   比别的点多了一次"只进不出"，于是 w 用掉的入边比出边多 1。但 w 的出边
   已经用光了（卡住 = num[w]=10），意味着入边用了 11 条 > 总入度 10，矛盾。
   所以贪心走到卡住时必然回到起点，走出的是一条闭合回路 C。

   C 通常只覆盖一小部分边（n=2 时 100 条里只走了 18 条）。剩余边挂在 C 的
   各顶点上，且对 C 上每个点，剩余的入度 = 出度（进出的消耗是配平的）。

   结论：回溯就是在"找挂着的子回路并插回去"
   ------------------------------------------------------------
   - 弹出一条边 e = (u→x)，概念上就是退回点 u；
   - 若 u 还剩边（num[u] < 10），从 u 再贪心走，按上面的论证还会卡回 u，
     形成一条子回路，正好插在 e 之前的位置；
   - 若 u 已经用完（num[u] == 10），no_dfs(u) 的 while 直接跳过，继续往上弹。

   所以"回溯时还有边"不是 bug，而是 Hierholzer 的核心机制：每条弹出边的起点
   都检查一次，把所有子回路逐个拼进主回路。当栈弹空时，每条边恰好被走过一次，
   欧拉回路完成。

   对应递归版 DFS 找欧拉回路里的同一个现象：子节点递归返回后，父节点的
   while 循环继续走它剩下的边——两者是同一件事。

   ============================================================
   三、st_ans 存的是什么？
   ============================================================

   不是只存 99 的末位。st_ans 只在弹栈那一步写入，且每弹一条边恰好写一个
   字符 edge % 10（边值的最后一位 d）。前向走的时候只压 st_edge，什么都不写。

   91~99 的完整账目（n=2，从 9 号点出发那次前向走）
   ------------------------------------------------------------
   压栈顺序：91, 11, 12, 21, 13, 31, ..., 88, 89, 99
   弹栈（后进先出），每弹一条往 st_ans 写一位：
       99（先弹） → '9'
       89         → '9'
       88         → '8'
       98         → '8'
       ...
       91（后弹） → '1'

   所以 91~99 这 9 条边每条都贡献一位，总共 9 位。全图 100 条边各写一次，
   st_ans 最后正好 100 位。

   为什么是逆序的
   ------------------------------------------------------------
   - 前向走：边按回路顺序压栈（91 在 99 前面）
   - 弹栈：按回路逆序弹出（99 先弹）→ st_ans[0] 存的是回路的最后一条边的末位
   - 所以最后打印要倒着输出：while(top_a) printf("%c", st_ans[--top_a]);

   倒序打印后，st_ans 里的内容按回路正序还原：91 的 '1' 出现在 99 的 '9'
   前面，正是最终答案的顺序。

   一句话：st_ans 存的是每条边的末位数字（完整边值的前 n-1 位就是上一个点，
   已由前一条边覆盖，只有末位是新增信息），每条边存一次、存在它被弹出的时刻，
   顺序是回路的逆序。
*/
