// ============================================================
// 洛谷 P7771 【模板】欧拉路径
// 求有向图字典序最小的欧拉路径 —— Hierholzer 算法
// ============================================================

#include <bits/stdc++.h>
using namespace std;

const int N = 1e5 + 5;
int n, m;
vector<int> g[N];
int in[N], out[N];
int cur[N];              // 每个点删边进度（邻接表已遍历到第几条边）
vector<int> ans;         // 回溯时记录，最后倒序输出

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n >> m;
    for (int i = 1; i <= m; i++) {
        int u, v;
        cin >> u >> v;
        g[u].push_back(v);
        out[u]++, in[v]++;
    }

    // 1. 判定：有向图欧拉路径的存在条件
    int s = -1, t = -1, ok = 1;
    for (int i = 1; i <= n; i++) {
        if (in[i] == out[i]) continue;
        if (out[i] - in[i] == 1 && s == -1) s = i;       // 起点：出度=入度+1
        else if (in[i] - out[i] == 1 && t == -1) t = i;  // 终点：入度=出度+1
        else { ok = 0; break; }                          // 其余差值情况不合法
    }
    if (!ok) { cout << "No\n"; return 0; }
    if (s == -1) s = 1;   // 所有点 in==out：是欧拉回路，从任意非零度点出发

    // 2. 字典序最小：邻接表从小到大排序
    for (int i = 1; i <= n; i++) sort(g[i].begin(), g[i].end());

    // 3. Hierholzer：迭代 DFS + 删边（m 可达 2e5，递归会爆栈）
    stack<int> st;
    st.push(s);
    while (!st.empty()) {
        int u = st.top();
        if (cur[u] < (int)g[u].size()) {
            st.push(g[u][cur[u]++]);   // 走一条边并"删掉"它
        } else {
            ans.push_back(u);          // u 的出边走完了，回溯记录
            st.pop();
        }
    }

    // 4. 走过的点数不足 m+1：图不连通（题目保证弱连通，此判断兜底）
    if ((int)ans.size() != m + 1) { cout << "No\n"; return 0; }

    for (int i = (int)ans.size() - 1; i >= 0; i--)   // 倒序输出
        cout << ans[i] << " \n"[i == 0];
    return 0;
}

/* ============================================================
   欧拉路径 / 欧拉回路 知识点
   ============================================================

   1. 定义
   ------------------------------------------------------------
   欧拉路径：恰好经过图中每条边一次的路径（不要求回到起点）
   欧拉回路：起点 = 终点的欧拉路径
   "一笔画"问题 = 判断是否存在欧拉路径

   2. 判定定理（只判断存在性，O(n)）
   ------------------------------------------------------------
   无向图：
     欧拉回路：所有点度数为偶数，且非零度点连通
     欧拉路径：恰有 0 或 2 个奇度点（2 个奇度点时它们分别是起终点），
               且非零度点连通
   有向图：
     欧拉回路：所有点 in == out，且弱连通
     欧拉路径：恰有一点 out = in + 1（起点）、一点 in = out + 1（终点），
               其余点 in == out，且弱连通
   弱连通：把有向边当作无向边后图连通

   3. Hierholzer 算法（求具体路径）O(n + m)
   ------------------------------------------------------------
   核心：从起点 DFS，每走一条边就删除该边，走到"死胡同"
   （出边全部走完）时把该点压入答案栈，最后倒序输出。
   cur[u] 记录删边进度，保证每条边只被扫描一次。

   为什么倒序：
   先到达"死胡同"的点，说明它后面已经没有未走的边，
   在合法路径中它必然靠后；回溯顺序的倒序恰好排对。

   4. 常见坑
   ------------------------------------------------------------
   - 边数大时递归 DFS 会爆栈，用显式 stack 迭代。
   - 无向图：双向建边，删除时反向边也要删
     （链式前向星存边编号，used[i] 与 used[i ^ 1] 同时标记）。
   - 重边、自环不影响算法：每条边独立存、独立删。
   - 若走过边数 != m，说明不连通或起点选错（题目不保证连通时要判）。

   5. 经典题
   ------------------------------------------------------------
   洛谷 P7771  有向图欧拉路径（本题）
   洛谷 P2731  [USACO3.3] 骑马修栅栏（无向图，字典序最小）
   洛谷 P1341  无序字母对（无向图）
   洛谷 P1127  词链（单词做边、字母做点）
*/
